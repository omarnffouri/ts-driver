/// Canonical semantic color tokens for the app.
///
/// - Brightness-agnostic tokens (e.g. [primary]) are identical in both modes.
/// - `light*` / `dark*` pairs are resolved by `ContextColorExtensions`
///   (theme_extensions.dart), so call sites use `context.panelColor` etc. and
///   never write `isDark ? darkX : lightX` by hand.
///
/// Values are seeded from the existing [AppColorsLight] / [AppColorsDark]
/// palettes to keep a single source of truth during the migration.
abstract final class AppColors {
  // ── Brightness-agnostic ────────────────────────────────────────────────
  static const Color primary = kMainColor; // #E21F26
  static const Color primaryDark = kMainColorDark;
  static const Color primaryLight = kMainColorLight;
  static const Color onPrimary = Colors.white;
  // Resting/secondary brand tone (e.g. unfocused field icons).
  static final Color mutedPrimary = primary.withValues(alpha: 0.55);

  // status
  static const Color success = Color(0xFF27AE60);
  static const Color warning = kAmberColor; // #FFA800
  // Deep amber that takes white text (full-strength [warning] is too light).
  static const Color warningDeep = Color(0xFFB26F00);
  static const Color error = kMainColor; // brand red (matches snackbar error)
  static const Color info = Color(0xFF2F80ED);

  // ── Backgrounds (scaffold) ─────────────────────────────────────────────
  // Dark mode uses a near-black neutral base with surfaces stepping up only
  // slightly — a proper elevation ladder (bg < surface < card < tile) so
  // depth reads cleanly and dividers stay visible between adjacent steps.
  static const Color lightBackground = AppColorsLight.scaffoldBackroundColor;
  static const Color darkBackground = Color(0xFF0E0E0F);

  // ── Surfaces (app bars / sheets / elevated) ────────────────────────────
  static const Color lightSurface = Colors.white;
  static const Color darkSurface = Color(0xFF161618);

  // ── Cards ──────────────────────────────────────────────────────────────
  static const Color lightCard = Colors.white;
  static const Color darkCard = Color(0xFF1C1C1E);

  // ── Tiles / list rows ──────────────────────────────────────────────────
  static const Color lightTile = Colors.white;
  static const Color darkTile = Color(0xFF242426);

  // ── Input fill (recessed form fields on a card) ────────────────────────
  // Light: a hair off white so the field reads as a soft recess on a white
  // card without the heavy page-grey slab. Dark: one step ABOVE the card so
  // the field reads raised, not as a black hole.
  static const Color lightInputFill = Color(0xFFF6F7F9);
  static const Color darkInputFill = darkTile; // one step above the dark card

  // ── Signature writing panel ────────────────────────────────────────────
  // Light panel + black ink in light mode; dark recessed panel + off-white ink
  // in dark (the on-screen ink follows [signatureInk]). The exported PNG is
  // ALWAYS black-on-light regardless — the SignatureController forces
  // exportPenColor black over a light export background (legal signature).
  static const Color lightSignaturePanel = Color(0xFFF4F5F7);
  static const Color darkSignaturePanel = darkTile; // recessed, like inputs
  // On-screen pen ink per panel tone (display only — never the exported color).
  static const Color lightSignatureInk = Colors.black;
  static const Color darkSignatureInk = darkTextPrimary;

  // ── Text ───────────────────────────────────────────────────────────────
  static const Color lightTextPrimary =
      AppColorsLight.secondaryHeaderColor; // #3E4958
  static const Color darkTextPrimary = Color(0xFFF2F3F5); // crisp off-white
  static const Color lightTextSecondary = AppColorsLight.textColor; // #656363
  static const Color darkTextSecondary = Color(0xFFA6A9AE);

  // ── Hints / placeholders ───────────────────────────────────────────────
  static const Color lightHint = kHintColor; // #82858A
  static const Color darkHint = Color(0xFF74787E);

  // ── Dividers / borders ─────────────────────────────────────────────────
  // Sits between card (#1C1C1E) and tile (#242426) so it reads on cards.
  static const Color lightDivider = Color(0xFFE9EBF0);
  static const Color darkDivider = Color(0xFF2C2C2E);

  // ── Shimmer (loading skeletons) ────────────────────────────────────────
  // base = the resting skeleton tone, highlight = the sweeping band.
  // Dark tones are warm-neutral (R >= B) so they never read blue — important
  // because the shimmer also sweeps content on the red header.
  static const Color lightShimmerBase = Color(0xFFE0E0E0);
  static const Color lightShimmerHighlight = Color(0xFFF5F5F5);
  static const Color darkShimmerBase = Color(0xFF2C2A29);
  static const Color darkShimmerHighlight = Color(0xFF3C3A38);

  // Shimmer on a colored/branded surface (e.g. the red header) — white-based
  // in both modes so it never reads as a muddy/blue grey against the brand.
  static const Color onColoredShimmerBase = Color(0x59FFFFFF); // white @ 35%
  static const Color onColoredShimmerHighlight =
      Color(0xB3FFFFFF); // white @ 70%

  // ── Header gradients ───────────────────────────────────────────────────
  // Light header (also the [AppRedHeader] default in light mode): brand red.
  static const LinearGradient brandHeaderGradient = LinearGradient(
    colors: [
      AppColorsLight.mainColorDark,
      AppColorsLight.mainColorLight,
      Color.fromARGB(255, 183, 30, 35),
    ],
    stops: [0.0, 0.5, 1.0],
    begin: Alignment.centerLeft,
    end: Alignment.centerRight,
  );
  // Dark header: a horizontal near-black → dark-red sweep.
  static const LinearGradient darkHeaderGradient = LinearGradient(
    colors: [
      Color(0xFF121212),
      Color(0xFF5A1618),
      Color(0xFF811818),
    ],
    stops: [0.0, 0.5, 1.0],
    begin: Alignment.centerLeft,
    end: Alignment.centerRight,
  );

  // ── Chat list ──────────────────────────────────────────────────────────
  // The conversation list paints on its own surface (one step above the
  // scaffold) so the dark sheet reads "dark but alive" instead of pure black.
  static const Color lightChatListBackground = Colors.white;
  static const Color darkChatListBackground = Color(0xFF15171A);
  // WhatsApp-native muted grey for previews + timestamps — AA on both tones.
  static const Color chatPreviewGrey = Color(0xFF8696A0);
  // Offline presence dot — muted grey (never the brand red, which collides
  // with the red header + red unread badge).
  static const Color lightOfflineDot = Color(0xFFB0B4BA);
  static const Color darkOfflineDot = Color(0xFF74787E);

  // ── Chat detail (conversation thread) ──────────────────────────────────
  // Received (incoming) bubble surface + the text/icons painted on it.
  // Dark surface sits between darkCard (#1C1C1E) and darkTile (#242426) so the
  // bubble reads elevated against the dark canvas without a harsh white.
  static const Color lightReceivedBubble = Colors.white;
  static const Color darkReceivedBubble = Color(0xFF262628);
  static const Color lightReceivedBubbleText = Color(0xFF1C1C1E);
  static const Color darkReceivedBubbleText = Color(0xFFECEEF0);
  // Sent (outgoing) bubble — brand red in both modes (text uses onPrimary).
  static const Color sentBubble = kMainColor;
  // Input pill surface + its drop shadow (transparent in dark).
  static const Color lightChatInputSurface = Colors.white;
  static const Color darkChatInputSurface = Color(0xFF1C1C1E);
  static const Color lightChatInputShadow = Color(0x1F000000);
  static const Color darkChatInputShadow = Color(0x00000000);
  // Message-list canvas painted behind the 20%-opacity pattern (NOT the global
  // scaffold token): light = scaffold grey, dark = a hair above darkBackground.
  static const Color lightChatCanvas = Color(0xFFF2F2F2);
  static const Color darkChatCanvas = Color(0xFF0F1011);
  // Neutral app-bar action icon (selection-mode copy) legible on either bar.
  static const Color lightChatAppBarIcon = Color(0xFF3E4958);
  static const Color darkChatAppBarIcon = Color(0xFFF2F3F5);
  // Read-receipt ticks rendered on a RECEIVED bubble (sent ticks use onPrimary).
  static const Color lightReceiptTick = Color(0xFF3E4958);
  static const Color darkReceiptTick = Color(0xFFA6A9AE);
  // Reaction chip surface floating above any bubble (border reuses background).
  static const Color lightReactionChip = Colors.white;
  static const Color darkReactionChip = Color(0xFF2C2C2E);
}
